import { describe, expect, it } from 'vitest'

import { formatPhone } from './format-phone'

describe('formatPhone', () => {
	it.each([
		['7', '+7'],
		['79', '+7 (9'],
		['7999', '+7 (999'],
		['79991', '+7 (999) 1'],
		['7999123', '+7 (999) 123'],
		['79991234', '+7 (999) 123-4'],
		['799912345', '+7 (999) 123-45'],
		['79991234567', '+7 (999) 123-45-67']
	])('постепенно форматирует российский номер: %s → %s', (value, expected) => {
		expect(formatPhone(value)).toBe(expected)
	})

	it.each([
		['3', '+3'],
		['37', '+37'],
		['375', '+375'],
		['3752', '+375 (2'],
		['375291234567', '+375 (29) 123-45-67']
	])('постепенно форматирует белорусский номер: %s → %s', (value, expected) => {
		expect(formatPhone(value)).toBe(expected)
	})

	it.each([
		['8', '+7'],
		['9', '+7 (9'],
		['8 999 123 45 67', '+7 (999) 123-45-67'],
		['+7 (999) 123-45-67', '+7 (999) 123-45-67'],
		['+375 (29) 123-45-67', '+375 (29) 123-45-67']
	])('приводит %s к маске %s', (value, expected) => {
		expect(formatPhone(value)).toBe(expected)
	})

	it('обрезает лишние цифры', () => {
		expect(formatPhone('799912345678')).toBe('+7 (999) 123-45-67')
		expect(formatPhone('3752912345678')).toBe('+375 (29) 123-45-67')
	})

	it('не применяет маску к неподдерживаемым кодам', () => {
		expect(formatPhone('+1 202 555 0123')).toBe('+12025550123')
	})

	it.each(['', '+', '(-)'])('возвращает пустую строку без цифр: «%s»', (value) => {
		expect(formatPhone(value)).toBe('')
	})
})
